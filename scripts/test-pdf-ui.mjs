  assert.equal(preserved.library.documents[0].recalls['unit-0'].answer, '저수지 A에서 탱크 B로 이동한다.');
  assert.equal(preserved.library.documents[0].pdf.pages[0].note, '화살표 A → B');
  assert.equal(preserved.storage.archivedCount, 0);
  await page.screenshot({ path: join(screenshots, 'search-restore.png') });
  assert.equal(errors.length, 0, JSON.stringify(errors));
  console.log('SQLite UI passed: original search, page evidence, compressed archive, archived search, restore and recall/note preservation.');
