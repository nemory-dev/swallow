import electronPath from 'electron';
import { fileURLToPath, pathToFileURL } from 'node:url';
const projectRoot = fileURLToPath(new URL('..', import.meta.url));
const modulePath = process.env.SWALLOW_PLAYWRIGHT_MODULE;
let electron;
try { ({ _electron: electron } = await import(modulePath ? pathToFileURL(modulePath).href : 'playwright')); }
catch { throw new Error('UI 검증은 선택 도구 Playwright가 필요합니다. SWALLOW_PLAYWRIGHT_MODULE에 설치된 playwright/index.mjs 절대 경로를 지정하세요. 앱 실행에는 필요하지 않습니다.'); }
import { mkdtemp, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { LibraryStore } from '../dist-electron/electron/library.js';
const data = await mkdtemp(join(tmpdir(), 'swallow-pdf-ui-'));
const screenshots = join(data, 'screenshots');
await mkdir(screenshots);
const errors = [];
const app = await electron.launch({ executablePath: electronPath, args: ['.'], cwd: projectRoot, env: { ...process.env, SWALLOW_DATA_DIR: data } });
try {
  const page = await app.firstWindow();
  page.on('pageerror', e => errors.push(e.message));
  await page.getByRole('heading', { name: '막막하면, 한 부분부터 같이 시작해요.' }).waitFor();
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, join(projectRoot, 'tests/fixtures/pdf/diagram.pdf'));
  await page.getByRole('button', { name: /PDF·텍스트 파일 가져오기/ }).click();
  await page.getByRole('button', { name: '자유 읽기', exact: true }).click();
  await page.locator('.pdf-page-preview img').waitFor({ timeout: 30000 });
  assert.match(await page.locator('.source-text').innerText(), /Water moves from reservoir A/);
  await page.screenshot({ path: join(screenshots, 'desktop.png') });
  await page.getByRole('button', { name: '그림·페이지 확대 ↗' }).click();
  await page.locator('.pdf-dialog[open]').waitFor();
  await page.getByRole('slider', { name: 'PDF 확대 비율' }).fill('200');
  await page.screenshot({ path: join(screenshots, 'zoom.png') });
  await page.locator('.pdf-dialog').getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('button', { name: '다음 쪽', exact: true }).click();
  await page.getByRole('button', { name: '학습 구간 1쪽으로' }).waitFor();
  await page.locator('.pdf-page-preview img[alt^="원본 PDF 2쪽"]').waitFor();
  await page.getByRole('button', { name: '학습 구간 1쪽으로' }).click();
  await page.locator('.pdf-page-preview img[alt^="원본 PDF 1쪽"]').waitFor();
  await page.locator('.pdf-note summary').click();
  await page.getByRole('textbox', { name: 'PDF 1쪽 그림 메모' }).fill('화살표 A → B');
  await page.getByRole('button', { name: '메모 저장', exact: true }).click();
  await page.locator('.source-heading').getByRole('button', { name: '회상을 위해 숨기기' }).click();
  assert.equal(await page.locator('.pdf-reader').count(), 0);
  await page.getByRole('textbox', { name: '회상 답안', exact: true }).fill('저수지 A에서 탱크 B로 이동한다.');
  await page.getByRole('button', { name: '답안 저장', exact: true }).click();
  const state = await page.evaluate(() => window.swallow.getState());
  const doc = state.library.documents[0];
  assert.equal(doc.pdf.pages[0].note, '화살표 A → B');
  assert.equal(doc.recalls['unit-0'].answer, '저수지 A에서 탱크 B로 이동한다.');
  assert.equal(errors.length, 0, JSON.stringify(errors));
  const verification = new LibraryStore(join(data, 'library.json'));
  await verification.load(); const library = verification.exportLibrary(); verification.close();
  assert.equal(library.documents.length, 1);
  console.log('Desktop PDF smoke passed: import, page image, zoom 200%, page navigation, note, hide, recall save. No renderer errors.');
  console.log('Temporary data: ' + data);
} finally { await app.close(); }
// Seed verified response shapes to check renderer evidence links without real AI usage.
const seeded = new LibraryStore(join(data, 'library.json')); await seeded.load();
const library = seeded.snapshot();
const doc = library.documents[0];
const evidence = [{ page: 1, description: '테스트 해석: A에서 B로 향하는 화살표', uncertainty: '비용 없는 대역 응답' }];
doc.guides['unit-0'] = { model: 'ui-test-model', guide: { overview: '테스트 가이드: 펌프가 A에서 B로 물을 전달합니다.', keyPoints: [{ title: '흐름', explanation: 'A → B', quote: 'Water moves from reservoir A to tank B through a pump.' }], question: '화살표 방향과 펌프의 역할은?', visualEvidence: evidence } };
doc.recalls['unit-0'].feedback = { assessment: '테스트 피드백: 방향 설명 확인', missingPoints: ['펌프의 역할'], nextStep: '원본 화살표를 확인하세요.', visualEvidence: evidence };
await seeded.update(() => library); seeded.close();
