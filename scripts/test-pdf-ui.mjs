  console.log('Evidence UI passed: guide, feedback, repeat original page links, hidden-source return. AI responses were synthetic.');
  await page.getByRole('button', { name: '원문 검색·보관 로컬' }).click();
  await page.getByRole('textbox', { name: '원문 검색어' }).fill('reservoir');
  await page.getByRole('button', { name: '검색', exact: true }).click();
  await page.locator('.search-results li').first().waitFor();
  await page.screenshot({ path: join(screenshots, 'local-search.png') });
  await page.locator('.search-results li').first().getByRole('button', { name: '원문 근거 보기 ↗' }).click();
  await page.locator('.pdf-page-preview img[alt^="원본 PDF 1쪽"]').waitFor();
  await page.getByRole('button', { name: '원문 검색·보관 로컬' }).click();
  await page.locator('.storage-controls summary').click();
  await page.getByRole('button', { name: '현재 문서 압축 보관', exact: true }).click();
  await page.locator('.archive-list').getByRole('button', { name: '복원', exact: true }).waitFor();
  await page.getByRole('textbox', { name: '원문 검색어' }).fill('reservoir');
  await page.getByRole('button', { name: '검색', exact: true }).click();
